# Старые и «чужие» имена классов → наши (метки из прошлых версий сайта, названия в открытых датасетах).
CLASS_ALIASES = {"cardboard": "paper", "trash": "other", "battery": "ewaste", "biological": "organic"}


def canonical(cls):
    """Имя класса в терминах WASTE_INFO: cardboard → paper, trash → other, …"""
    return CLASS_ALIASES.get(cls, cls)


# Батарейки и электроника — опасные отходы: им нельзя в обычный бак и в контейнеры для вторсырья.
HAZARD_SURE = ("⚠️ **Опасные отходы — только в спецпункт.** Батарейки, аккумуляторы и электронику нельзя "
               "выбрасывать в мусорный бак и в контейнеры для вторсырья. Сдайте их в бокс для батареек "
               "(часто стоят в супермаркетах, торговых центрах и школах) или в пункт приёма электроники.")
HAZARD_MAYBE = ("🔋 Если на фото батарейка, аккумулятор или электроника — их сдают только в специальные "
                "пункты приёма, не в обычный мусор.")
HAZARD_MAYBE_MIN = 0.20  # «может быть, это батарейка» — с какой вероятности второго варианта предупреждаем


def hazard_hint(ranked):
    """Подсказка про спецпункты по ответу модели [(класс, вероятность), …].

    "sure"  — первый вариант модели: батарейки/электроника;
    "maybe" — это второй или третий вариант с вероятностью от 20%: пропустить батарейку хуже,
              чем лишний раз напомнить про спецпункт;
    None    — опасных вариантов нет (или модель такого класса не знает).
    """
    for place, (cls, prob) in enumerate(ranked):
        if WASTE_INFO.get(canonical(cls), {}).get("hazardous"):
            if place == 0:
                return "sure"
            if prob >= HAZARD_MAYBE_MIN:
                return "maybe"
    return None

