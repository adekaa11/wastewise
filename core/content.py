# Уровни в профиле: с какого числа баллов, название, значок. Шаги растут — каждый следующий уровень труднее.
LEVELS = [
    (0, "Новичок", "🌱"),
    (50, "Сортировщик", "♻️"),
    (150, "Эко-активист", "🌿"),
    (400, "Эко-герой", "🌍"),
    (1000, "Легенда переработки", "🏆"),
]


def level_for(points):
    """Текущий уровень и следующий (None, если уровень максимальный): ((порог, название, значок), …)."""
    current = LEVELS[0]
    for lvl in LEVELS:
        if points >= lvl[0]:
            current = lvl
    following = next((lvl for lvl in LEVELS if lvl[0] > points), None)
    return current, following
